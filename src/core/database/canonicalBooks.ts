/**
 * Normaliza una cadena eliminando diacríticos, mayúsculas y caracteres especiales
 */
function normalizeForSearch(text: string): string {
  return text
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .trim();
}

/**
 * Busca de forma resiliente y determinista cualquiera de los 66 libros de la Biblia
 * reconociendo nombres canónicos, variaciones sin acentos y abreviaturas oficiales.
 */
export function findCanonicalBook(input: string): CanonicalBookProfile | null {
  if (!input || input.trim().length === 0) return null;

  const normalizedInput = normalizeForSearch(input);
  const words = normalizedInput.split(/[\s,.;:!?()\-_/\\]+/).filter((w) => w.length > 0);

  // 1. Coincidencia exacta con nombre canónico o sin tilde
  for (const book of CANONICAL_BOOKS_CATALOG) {
    const bookNorm = normalizeForSearch(book.nombre);
    if (normalizedInput === bookNorm) {
      return book;
    }
  }

  // 2. Coincidencia por frases comunes: "libro de X", "evangelio de X", "carta a X"
  for (const book of CANONICAL_BOOKS_CATALOG) {
    const bookNorm = normalizeForSearch(book.nombre);
    if (
      normalizedInput.includes(`libro de ${bookNorm}`) ||
      normalizedInput.includes(`evangelio de ${bookNorm}`) ||
      normalizedInput.includes(`evangelio segun san ${bookNorm}`) ||
      normalizedInput.includes(`carta a los ${bookNorm}`) ||
      normalizedInput.includes(`epistola a los ${bookNorm}`) ||
      normalizedInput.includes(`epistola de ${bookNorm}`) ||
      normalizedInput.includes(`profecia de ${bookNorm}`)
    ) {
      return book;
    }
  }

  // 3. Coincidencia por palabra clave dentro de la consulta
  for (const book of CANONICAL_BOOKS_CATALOG) {
    const bookNorm = normalizeForSearch(book.nombre);
    // Para libros con números (1 Samuel, 2 Reyes, 1 Corintios, etc.)
    if (bookNorm.includes(' ')) {
      if (normalizedInput.includes(bookNorm)) {
        return book;
      }
    } else {
      if (words.includes(bookNorm)) {
        return book;
      }
    }
  }

  // 4. Coincidencia por abreviaturas oficiales o alternativas
  for (const book of CANONICAL_BOOKS_CATALOG) {
    const abbrevNorm = normalizeForSearch(book.abreviatura);
    if (words.includes(abbrevNorm)) {
      return book;
    }

    for (const alt of book.abreviaturasAlternativas) {
      const altNorm = normalizeForSearch(alt);
      if (words.includes(altNorm)) {
        return book;
      }
    }
  }

  return null;
}
